// pnpm n8n:setup
//
// Prepares the local n8n stack:
//  1. generates the shared HMAC secret (32 random bytes) unless n8n.env already has one
//  2. stores it in the Convex deployment as LENDLOOP_HMAC_SECRET
//  3. writes n8n.env (git-ignored) with the secret, the Convex HTTP URL and the
//     app URL used for links in emails
// The secret is never printed. Options:
//   --rotate            replace an existing secret
//   --app-url <url>     where the Next.js app runs (default http://localhost:3000)

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { setConvexEnv } from "./convex-env.mjs";

const N8N_ENV = "n8n.env";
const rotate = process.argv.includes("--rotate");
const appUrlFlag = process.argv.indexOf("--app-url");
const appUrlArg = appUrlFlag === -1 ? undefined : process.argv[appUrlFlag + 1];

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) values[match[1]] = match[2];
  }
  return values;
}

const convexUrl = readEnvFile(".env.local").NEXT_PUBLIC_CONVEX_SITE_URL;
if (!convexUrl) {
  console.error("NEXT_PUBLIC_CONVEX_SITE_URL is missing from .env.local. Run `pnpm convex dev` once first.");
  process.exit(1);
}

const current = readEnvFile(N8N_ENV);
const secret =
  current.LENDLOOP_HMAC_SECRET && !rotate
    ? current.LENDLOOP_HMAC_SECRET
    : randomBytes(32).toString("hex");

if (!setConvexEnv("LENDLOOP_HMAC_SECRET", secret)) {
  console.error("Could not set LENDLOOP_HMAC_SECRET in Convex (is `pnpm convex dev` set up?).");
  process.exit(1);
}

const appUrl = (appUrlArg ?? current.LENDLOOP_APP_URL ?? "http://localhost:3000").replace(/\/$/, "");
const next = {
  ...current,
  LENDLOOP_HMAC_SECRET: secret,
  LENDLOOP_CONVEX_URL: convexUrl,
  LENDLOOP_APP_URL: appUrl,
};
writeFileSync(
  N8N_ENV,
  "# Generated by `pnpm n8n:setup`. Git-ignored; never commit.\n" +
    Object.entries(next)
      .map(([key, value]) => `${key}=${value}`)
      .join("\n") +
    "\n",
);

console.log(`✔ LENDLOOP_HMAC_SECRET ${rotate || !current.LENDLOOP_HMAC_SECRET ? "generated" : "kept"} (not shown)`);
console.log("✔ stored in Convex and in n8n.env");
console.log(`✔ LENDLOOP_CONVEX_URL=${convexUrl}`);
console.log(`✔ LENDLOOP_APP_URL=${appUrl}`);
console.log("Next: docker compose up -d, then pnpm tunnel");
