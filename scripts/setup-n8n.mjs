// pnpm n8n:setup
//
// Prepares the local n8n stack:
//  1. generates the shared HMAC secret (32 random bytes), or keeps the existing one
//  2. stores it in the Convex deployment as LENDLOOP_HMAC_SECRET
//  3. writes it to .n8n-hmac-secret (git-ignored) so you can paste it into the
//     n8n "LendLoop HMAC secret" credential. It is NOT put in n8n's environment,
//     so no workflow can read it via $env; only the Crypto credential holds it.
//  4. writes n8n.env (git-ignored, the container's environment) with the
//     non-secret settings: Convex HTTP URL and app URL for links in emails
// The secret is never printed. Options:
//   --rotate            replace the existing secret (update the n8n credential too)
//   --app-url <url>     where the Next.js app runs (default http://localhost:3000)

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { setConvexEnv } from "./convex-env.mjs";

const N8N_ENV = "n8n.env";
const SECRET_FILE = ".n8n-hmac-secret";
const rotate = process.argv.includes("--rotate");
const appUrlFlag = process.argv.indexOf("--app-url");
const appUrlArg = appUrlFlag === -1 ? undefined : process.argv[appUrlFlag + 1];

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) values[match[1]] = match[2];
  }
  return values;
}

const convexUrl = readEnvFile(".env.local").NEXT_PUBLIC_CONVEX_SITE_URL;
if (!convexUrl) {
  console.error("NEXT_PUBLIC_CONVEX_SITE_URL is missing from .env.local. Run `pnpm convex dev` once first.");
  process.exit(1);
}

const current = readEnvFile(N8N_ENV);
// Earlier versions kept the secret in n8n.env; reuse it so nothing needs re-pasting.
const existingSecret = existsSync(SECRET_FILE)
  ? readFileSync(SECRET_FILE, "utf8").trim()
  : current.LENDLOOP_HMAC_SECRET;
const secret = existingSecret && !rotate ? existingSecret : randomBytes(32).toString("hex");

if (!setConvexEnv("LENDLOOP_HMAC_SECRET", secret)) {
  console.error("Could not set LENDLOOP_HMAC_SECRET in Convex (is `pnpm convex dev` set up?).");
  process.exit(1);
}
writeFileSync(SECRET_FILE, secret + "\n");

const appUrl = (appUrlArg ?? current.LENDLOOP_APP_URL ?? "http://localhost:3000").replace(/\/$/, "");
writeFileSync(
  N8N_ENV,
  [
    "# Generated by `pnpm n8n:setup`. Git-ignored. No secrets here: the HMAC secret",
    "# lives only in the n8n Crypto credential (copied from .n8n-hmac-secret).",
    `LENDLOOP_CONVEX_URL=${convexUrl}`,
    `LENDLOOP_APP_URL=${appUrl}`,
    "",
  ].join("\n"),
);

const fresh = rotate || !existingSecret;
console.log(`✔ HMAC secret ${fresh ? "generated" : "kept"} (not shown) → Convex + ${SECRET_FILE}`);
if (fresh) console.log(`  Paste it into the n8n credential "LendLoop HMAC secret" (Hmac Secret field).`);
console.log(`✔ n8n.env: LENDLOOP_CONVEX_URL=${convexUrl}`);
console.log(`✔ n8n.env: LENDLOOP_APP_URL=${appUrl}`);
console.log("Next: docker compose up -d, then pnpm tunnel");
